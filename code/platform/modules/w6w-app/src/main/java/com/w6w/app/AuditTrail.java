package com.w6w.app;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.annotation.PostConstruct;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;
import java.util.Map;

/** Local append-only event log for user and operator actions. */
@Service
public class AuditTrail {
    private final JdbcTemplate jdbc;
    private final ObjectMapper json;

    public AuditTrail(JdbcTemplate jdbc, ObjectMapper json) {
        this.jdbc = jdbc;
        this.json = json;
    }

    @PostConstruct
    void createTable() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS w6w_audit_event ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "instance_id VARCHAR(64), workflow_key VARCHAR(128), business_key VARCHAR(255), "
                + "task_id VARCHAR(64), actor VARCHAR(255) NOT NULL, action VARCHAR(40) NOT NULL, "
                + "details CLOB NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_w6w_audit_instance ON w6w_audit_event(instance_id, id)");
    }

    public void record(String instanceId, String workflowKey, String businessKey, String taskId,
                       String actor, String action, Map<String, ?> details) {
        String payload;
        try { payload = json.writeValueAsString(details == null ? Map.of() : details); }
        catch (JsonProcessingException e) { throw new IllegalArgumentException("Audit details could not be serialized", e); }
        jdbc.update("INSERT INTO w6w_audit_event(instance_id, workflow_key, business_key, task_id, actor, action, details, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                instanceId, workflowKey, businessKey, taskId, actor, action, payload, Timestamp.from(Instant.now()));
    }

    public List<Map<String, Object>> list(String instanceId, int limit) {
        int capped = Math.max(1, Math.min(limit, 1000));
        String sql = "SELECT id, instance_id, workflow_key, business_key, task_id, actor, action, details, created_at "
                + "FROM w6w_audit_event " + (instanceId == null || instanceId.isBlank() ? "" : "WHERE instance_id = ? ")
                + "ORDER BY id DESC LIMIT ?";
        if (instanceId == null || instanceId.isBlank())
            return jdbc.queryForList(sql, capped).stream().map(this::row).toList();
        return jdbc.queryForList(sql, instanceId, capped).stream().map(this::row).toList();
    }

    private Map<String, Object> row(Map<String, Object> row) {
        Object createdAt = row.get("CREATED_AT");
        if (createdAt instanceof java.time.OffsetDateTime timestamp) row.put("CREATED_AT", timestamp.toInstant().toString());
        else if (createdAt instanceof Timestamp timestamp) row.put("CREATED_AT", timestamp.toInstant().toString());
        Map<String, Object> normalized = new java.util.LinkedHashMap<>();
        row.forEach((key, value) -> normalized.put(switch (key) {
            case "ID" -> "id"; case "INSTANCE_ID" -> "instanceId"; case "WORKFLOW_KEY" -> "workflowKey";
            case "BUSINESS_KEY" -> "businessKey"; case "TASK_ID" -> "taskId"; case "ACTOR" -> "actor";
            case "ACTION" -> "action"; case "DETAILS" -> "details"; case "CREATED_AT" -> "createdAt";
            default -> key;
        }, value));
        return normalized;
    }
}
